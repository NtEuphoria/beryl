#!/usr/bin/env python3
"""Embeds runtime/beryl_rt.{h,c} into src/back/runtime_embed.h.

The compiler writes these two files into its cache directory before invoking
clang, which keeps `beryl` a single self-contained binary with no lib/ path to
locate at run time. Regenerated by scripts/build.sh; the result is committed so
a build never requires Python.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def as_c_string(text: str) -> str:
    out = []
    for line in text.splitlines(keepends=True):
        esc = (
            line.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
            .replace("\t", "\\t")
            .replace("\r", "")
        )
        out.append(f'    "{esc}"')
    return "\n".join(out) if out else '    ""'


def main() -> int:
    hdr = (ROOT / "runtime" / "beryl_rt.h").read_text(encoding="utf-8")
    src = (ROOT / "runtime" / "beryl_rt.c").read_text(encoding="utf-8")

    out = ROOT / "src" / "back" / "runtime_embed.h"
    out.write_text(
        "/* Generated by scripts/embed_runtime.py. Do not edit.\n"
        " * Source of truth: runtime/beryl_rt.h and runtime/beryl_rt.c */\n"
        "#ifndef BERYL_RUNTIME_EMBED_H\n"
        "#define BERYL_RUNTIME_EMBED_H\n\n"
        "static const char *const BERYL_RT_H =\n"
        f"{as_c_string(hdr)};\n\n"
        "static const char *const BERYL_RT_C =\n"
        f"{as_c_string(src)};\n\n"
        "#endif /* BERYL_RUNTIME_EMBED_H */\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"embedded runtime -> {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
